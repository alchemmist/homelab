"""Pure offline regression suite; fixtures are not production executions."""

import contextlib
import copy
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
from typing import override

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "failure_policy", ROOT / "scripts/n8n/check_failure_alerts.py"
)
policy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(policy)


def _documents(value: object) -> list[dict[str, object]]:
    """Return the assert-verified list-of-mappings view of a parsed value."""
    assert isinstance(value, list)
    documents: list[dict[str, object]] = value
    return documents


def _mapping(value: object) -> dict[str, object]:
    """Return the assert-verified mapping view of a parsed value."""
    assert isinstance(value, dict)
    result: dict[str, object] = value
    return result


class WorkflowPolicyTests(unittest.TestCase):
    """Validate n8n workflow policy gating alert deployments."""
    @override
    def setUp(self) -> None:
        """Install the policy config and a workflows root."""

        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.config = {
            "version": 1,
            "handler_id": "handler1",
            "handler_name": "Failure Handler",
            "handler_template": None,
            "workflow_roots": ["workflows"],
        }
        self.put(policy.POLICY, self.config)
        (self.root / "workflows").mkdir()

    def put(self, path, data) -> Path:
        """Write a JSON fixture under the per-test policy root."""
        p: Path = self.root / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(data, indent=2) + "\n")
        return p

    def workflow(self, **settings) -> dict[str, object]:
        """Build an example workflow document with optional extra settings."""
        return {
            "name": "Example",
            "nodes": [
                {
                    "name": "Run",
                    "type": "n8n-nodes-base.code",
                    "parameters": {"jsCode": "return items;"},
                    "credentials": {"native": {"id": "reference-only"}},
                }
            ],
            "connections": {},
            "settings": {"executionTimeout": 60, **settings},
        }

    def run_policy(self, fix=False) -> int:
        """Run the policy checker over the per-test policy root."""
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            exit_code: int = policy.run(self.root, fix)
        return exit_code

    def test_check_fails_without_writing_and_fix_only_adds_setting(self) -> None:
        """Check fails without writes; fix adds only the setting."""

        w = self.workflow()
        p = self.put("workflows/new.json", w)
        before = p.read_bytes()
        assert self.run_policy() == 1
        assert p.read_bytes() == before
        assert self.run_policy(True) == 0
        expected = copy.deepcopy(w)
        _mapping(expected["settings"])["errorWorkflow"] = "handler1"
        assert json.loads(p.read_text()) == expected
        fixed = p.read_bytes()
        assert self.run_policy(True) == 0
        assert p.read_bytes() == fixed

    def test_missing_settings_can_be_generated(self) -> None:
        """A missing settings block is generated by fix."""

        w = self.workflow()
        del w["settings"]
        p = self.put("workflows/new.json", w)
        assert self.run_policy(True) == 0
        assert json.loads(p.read_text())["settings"] == {"errorWorkflow": "handler1"}

    def test_discovery_includes_new_nested_files(self) -> None:
        """Discovery picks up newly nested workflow files."""

        self.put("workflows/existing.json", self.workflow(errorWorkflow="handler1"))
        assert self.run_policy() == 0
        self.put("workflows/new/path/workflow.json", self.workflow())
        assert self.run_policy() == 1

    def test_other_handler_conflict_is_not_overwritten_or_partially_fixed(self) -> None:
        """A conflicting handler is never partially fixed."""

        missing = self.put("workflows/missing.json", self.workflow())
        other = self.put("workflows/other.json", self.workflow(errorWorkflow="another"))
        before = (missing.read_bytes(), other.read_bytes())
        assert self.run_policy(True) == 1
        assert (missing.read_bytes(), other.read_bytes()) == before

    def test_array_exports(self) -> None:
        """Array exports are repaired in place."""

        p = self.put(
            "workflows/export.json", [self.workflow(), self.workflow(errorWorkflow="handler1")]
        )
        assert self.run_policy(True) == 0
        assert all(w["settings"]["errorWorkflow"] == "handler1" for w in json.loads(p.read_text()))

    def handler(self) -> Path:
        """Install the explicit failure-handler template described by the config."""
        self.config["handler_template"] = "workflows/handler.json"
        self.put(policy.POLICY, self.config)
        w = self.workflow()
        w["name"] = "Failure Handler"
        _documents(w["nodes"])[0]["type"] = "n8n-nodes-base.errorTrigger"
        return self.put("workflows/handler.json", w)

    def test_only_explicit_handler_is_exempt(self) -> None:
        """Only the explicitly configured handler is exempt."""

        self.handler()
        assert self.run_policy() == 0
        w = self.workflow()
        w["name"] = "Failure Handler"
        _documents(w["nodes"])[0]["type"] = "n8n-nodes-base.errorTrigger"
        self.put("workflows/other.json", w)
        assert self.run_policy() == 1

    def test_handler_recursion_is_rejected_not_removed_by_fix(self) -> None:
        """Handler recursion is rejected, not removed by fix."""

        p = self.handler()
        w = json.loads(p.read_text())
        w["settings"]["errorWorkflow"] = "handler1"
        self.put("workflows/handler.json", w)
        assert self.run_policy(True) == 1
        assert json.loads(p.read_text())["settings"]["errorWorkflow"] == "handler1"

    def test_handler_identity_and_presence_fail_closed(self) -> None:
        """Missing or empty handlers fail closed."""

        p = self.handler()
        w = json.loads(p.read_text())
        w["nodes"] = []
        self.put("workflows/handler.json", w)
        assert self.run_policy() == 1
        p.unlink()
        assert self.run_policy() == 1

    def test_duplicate_keys_and_invalid_json_fail_closed(self) -> None:
        """Duplicate keys and invalid JSON fail closed."""

        p = self.put("workflows/bad.json", self.workflow())
        p.write_text('{"name":"one","name":"two"}')
        assert self.run_policy(True) == 1
        p.write_text("{invalid")
        assert self.run_policy(True) == 1

    def test_bad_settings_or_missing_connections_is_not_silently_skipped(self) -> None:
        """Bad settings or connections are never skipped silently."""

        w = self.workflow()
        w["settings"] = None
        self.put("workflows/bad.json", w)
        assert self.run_policy(True) == 1
        w = self.workflow()
        del w["connections"]
        self.put("workflows/bad.json", w)
        assert self.run_policy(True) == 1

    def test_symlink_and_path_traversal_rejected(self) -> None:
        """Symlinks and path traversal are rejected."""

        self.put("workflows/valid.json", self.workflow(errorWorkflow="handler1"))
        (self.root / "workflows/link.json").symlink_to(self.root / policy.POLICY)
        with self.assertRaises(ValueError):
            self.run_policy(True)
        (self.root / "workflows/link.json").unlink()
        self.config["workflow_roots"] = ["../outside"]
        self.put(policy.POLICY, self.config)
        with self.assertRaises(ValueError):
            self.run_policy(True)

    def test_symlinked_subdirectory_cannot_hide_unchecked_templates(self) -> None:
        """A symlinked subdirectory cannot hide templates."""

        self.put("workflows/valid.json", self.workflow(errorWorkflow="handler1"))
        self.put("elsewhere/hidden.json", self.workflow())
        (self.root / "workflows/hidden").symlink_to(
            self.root / "elsewhere", target_is_directory=True
        )
        with self.assertRaises(ValueError):
            self.run_policy(True)

    def test_empty_discovery_is_not_a_green_check(self) -> None:
        """An empty discovery is not a green check."""

        assert self.run_policy() == 1

    def test_actual_repository_policy(self) -> None:
        """The actual repository passes the policy unmodified."""

        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            assert policy.run(ROOT) == 0


if __name__ == "__main__":
    unittest.main()
