"""Compile one closed HTTP admission bit from the owner's complete Argo render."""

import argparse
import subprocess

import yaml

from ci.quality.public_web import CATALOG, ROOT

APP = "format-quorum"
HOST = "fq.alchemmist.xyz"
PIN = "format-quorum-tls"
OUTPUT = ROOT / "deploy/public-web/closed-format-quorum.yaml"


def eligible(items, catalog):
    """An unsupported route or service is withdrawn, never partially translated."""
    pin = catalog["hosts"].get(APP, {}).get(HOST, {})
    if pin != {"dns": "managed", "tlsSourceName": PIN}:
        return False
    owners = [r for r in items if r["kind"] == "Ingress"]
    backends = [r for r in items if r["kind"] == "Service" and r["metadata"]["name"] == APP]
    if (
        len(owners) != 1
        or len(backends) != 1
        or any(
            r["kind"] in {"IngressRoute", "HTTPRoute", "IngressRouteTCP", "TLSRoute"} for r in items
        )
    ):
        return False
    ing, svc = owners[0], backends[0]
    for obj in (ing, svc):
        if obj["metadata"]["name"] != APP or obj["metadata"].get("namespace") != APP:
            return False
    return (
        ing["apiVersion"] == "networking.k8s.io/v1"
        and svc["apiVersion"] == "v1"
        and ing["metadata"].get("labels", {}).get("homelab.alchemmist.xyz/public-web") == "true"
        and ing["metadata"].get("annotations")
        == {"cert-manager.io/cluster-issuer": "letsencrypt-http01"}
        and ing["spec"]
        == {
            "ingressClassName": "traefik",
            "tls": [{"hosts": [HOST], "secretName": PIN}],
            "rules": [
                {
                    "host": HOST,
                    "http": {
                        "paths": [
                            {
                                "path": "/",
                                "pathType": "Prefix",
                                "backend": {"service": {"name": APP, "port": {"number": 80}}},
                            }
                        ]
                    },
                }
            ],
        }
        and not svc["metadata"].get("annotations")
        and svc["spec"]
        == {
            "selector": {"app.kubernetes.io/name": APP, "app.kubernetes.io/instance": APP},
            "ports": [{"name": "http", "port": 80, "targetPort": 3000}],
        }
    )


def render():
    spec = yaml.safe_load((ROOT / "deploy/argocd/apps/format-quorum.yaml").read_text())["spec"]
    src = spec["source"]
    helm = src["helm"]
    if (
        "sources" in spec
        or src
        != {
            "repoURL": "https://github.com/alchemmist/homelab.git",
            "targetRevision": "main",
            "path": "charts/format-quorum",
            "helm": {
                "releaseName": APP,
                "valueFiles": ["../../deploy/format-quorum/values.yaml"],
                "parameters": [],
            },
        }
        or spec["destination"] != {"namespace": APP, "server": "https://kubernetes.default.svc"}
    ):
        raise ValueError("unreviewed Format Quorum release inputs")
    chart = ROOT / src["path"]
    values = chart / helm["valueFiles"][0]
    raw = subprocess.check_output(
        ["helm", "template", APP, str(chart), "-n", APP, "-f", str(values)]
    )
    allowed = eligible(
        [d for d in yaml.safe_load_all(raw) if d], yaml.safe_load(CATALOG.read_text())
    )
    return "# Generated by python -m ci.quality.closed_format_quorum\n" + yaml.safe_dump(
        {"closedFormatQuorum": allowed}
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = render()
    if args.check:
        return int(not OUTPUT.is_file() or OUTPUT.read_text() != value)
    OUTPUT.write_text(value)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
