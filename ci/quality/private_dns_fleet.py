"""Render the private DNS-only GitOps bundle; never apply resources or query live DNS."""

import argparse
import json
import subprocess

import yaml

from ci.quality.public_web import CATALOG, ROOT, replica_values

NAMESPACE = "public-dns-rehearsal"
OUTPUT = ROOT / "deploy/public-web/private-dns-fleet/resources.yaml"
SERIAL = 2026112601  # Private-stage SOA only, never transfer this zone to production.


def render() -> str:
    """Build each closed authority from the common chart and trusted inventory."""
    catalog = yaml.safe_load(CATALOG.read_text())
    documents = []
    for name, instance in sorted(catalog["replicas"].items()):
        values = replica_values(catalog, instance, SERIAL)
        values["stage"] = "dns-only"
        raw = subprocess.check_output(
            [
                "helm",
                "template",
                f"authority-{name}",
                str(ROOT / "deploy/public-web/replica"),
                "-n",
                NAMESPACE,
                "-f",
                "-",
            ],
            input=json.dumps(values),
            text=True,
        )
        documents.append(raw.rstrip())
    return (
        "# Generated by python -m ci.quality.private_dns_fleet; do not edit.\n"
        + "\n".join(documents)
        + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        return int(not OUTPUT.exists() or OUTPUT.read_text() != content)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
