"""Render the private DNS-only GitOps bundle; never apply resources or query live DNS."""

import argparse
import json
import subprocess

import yaml

from ci.quality.public_web import CATALOG, ROOT, replica_values

NAMESPACE = "public-dns-rehearsal"
OUTPUT = ROOT / "deploy/public-web/private-dns-fleet/resources.yaml"
SERIAL = 2026112601  # Private-stage SOA only, never transfer this zone to production.


class ManifestDumper(yaml.SafeDumper):
    """Keep generated multi-line Corefiles and zone files readable."""


def _string(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    return dumper.represent_scalar(
        "tag:yaml.org,2002:str", value, style="|" if "\n" in value else None
    )


ManifestDumper.add_representer(str, _string)


def render() -> str:
    """Build each closed authority from the common chart and trusted inventory."""
    catalog = yaml.safe_load(CATALOG.read_text())
    documents = []
    for name, instance in sorted(catalog["replicas"].items()):
        values = replica_values(catalog, instance, SERIAL)
        values["stage"] = "dns-only"
        raw = subprocess.check_output(
            [
                "helm",
                "template",
                f"authority-{name}",
                str(ROOT / "deploy/public-web/replica"),
                "-n",
                NAMESPACE,
                "-f",
                "-",
            ],
            input=json.dumps(values),
            text=True,
        )
        documents.extend(doc for doc in yaml.safe_load_all(raw) if doc)
    # Helm versions may insert different comments/blank lines between objects.
    # Normalize outer YAML, not the contents of ConfigMap data or their checksum.
    return "# Generated by python -m ci.quality.private_dns_fleet; do not edit.\n" + yaml.dump_all(
        documents, Dumper=ManifestDumper, sort_keys=False, explicit_start=True, width=120
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        return int(not OUTPUT.exists() or OUTPUT.read_text() != content)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
