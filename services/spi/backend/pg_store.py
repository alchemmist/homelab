"""SPI's fixed SQL vocabulary on PostgreSQL; values are always driver parameters."""
import re
from contextlib import contextmanager
from functools import lru_cache
import psycopg
from psycopg.rows import dict_row

class Row(dict):
    def __iter__(self):return iter(self.values())
    def __getitem__(self,key):
        return tuple(self.values())[key] if isinstance(key,int) else super().__getitem__(key)

def factory(cursor):
    make=dict_row(cursor)
    return lambda values: Row(make(values))

@lru_cache(maxsize=256)
def statement(s):
    if s.lstrip().upper().startswith('CREATE '):
        return re.sub(r'\bREAL\b','DOUBLE PRECISION',re.sub(r'\bINTEGER\b','BIGINT',s)).replace('id BIGINT PRIMARY KEY,','id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
    if 'INSERT OR IGNORE' in s:s=s.replace('INSERT OR IGNORE','INSERT')+' ON CONFLICT DO NOTHING'
    if 'INSERT OR REPLACE' in s:
        t=re.search(r'INTO (\w+)',s)[1];key,*cols={'job_failure_budget':['job_id','failures'],'match_review_v3':['job_id','progress'],'snapshot_budget':['job_id','replacements','retained'],'dispatch':['singleton','token','deadline','attempts'],'llm_rate_metadata':['job_id','metadata']}[t];s=s.replace('INSERT OR REPLACE','INSERT')+' ON CONFLICT ('+key+') DO UPDATE SET '+','.join(c+'=excluded.'+c for c in cols)
    s=s.replace('MIN(2,failures+1)','least(2,analysis_output_budget.failures+1)').replace('SET failures=failures+1','SET failures=job_failure_budget.failures+1').replace('MAX(observed,excluded.observed)','greatest(telegram_receipt_events.observed,excluded.observed)').replace('MAX(unknown,excluded.unknown)','greatest(telegram_receipt_events.unknown,excluded.unknown)')
    for a,b in [('max(tokens,?)','greatest(tokens,?)'),('max(available,?)','greatest(available,?)'),('min(expires,deadline)','least(expires,deadline)'),('max(available,lease)','greatest(available,lease)')]:s=s.replace(a,b)
    # SQL-only ASCII fold mirrors SQLite NOCASE, including cursor/keyset order.
    s=s.replace("coalesce(substr(json_extract(j.event,'$.labels.alertname'),1,200),'') COLLATE NOCASE", "translate(coalesce(substr(json_extract(j.event,'$.labels.alertname'),1,200),''),'ABCDEFGHIJKLMNOPQRSTUVWXYZ','abcdefghijklmnopqrstuvwxyz') COLLATE \"C\"")
    s=re.sub(r"json_array_length\(([\w.]+),'\$\.([\w.]+)'\)",r"json_array_length(json_extract(\1,'$.\2'))",s)
    s=re.sub(r"json_array_length\(json_extract\(([\w.]+),'\$\.([\w.]+)'\)\)",lambda m:"json_array_length("+m[1]+"::json #> '{"+m[2].replace('.',',')+"}')",s)
    s=re.sub(r"json_extract\(([\w.]+),'\$\.([\w.]+)'\)",lambda m:"("+m[1]+"::json #>> '{"+m[2].replace('.',',')+"}')",s)
    return s.replace('?', '%s')

class Conn:
    def __init__(self,db):self.db=db
    def execute(self,s,p=()):return self.db.execute(statement(s),p or None)
    def executemany(self,s,rows):return self.db.cursor().executemany(statement(s),rows)
    def executescript(self,s):
        for part in s.split(';'):
            if part.strip():self.execute(part)

@contextmanager
def connection(url, *, read_only=False):
    with psycopg.connect(url,connect_timeout=5,row_factory=factory) as db:
        if read_only:
            # A consistent MVCC snapshot without joining the queue of writers.
            db.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY')
        db.execute("SET LOCAL lock_timeout='15s'")
        # Same scope as BEGIN IMMEDIATE: all owner/budget/checkpoint updates share one lock.
        if not read_only:
            db.execute('SELECT pg_advisory_xact_lock(1397770577)')
        yield Conn(db)
