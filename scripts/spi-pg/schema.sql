CREATE TABLE jobs (
              id TEXT PRIMARY KEY, episode TEXT NOT NULL, event TEXT NOT NULL,
              stage BIGINT NOT NULL DEFAULT 0, state TEXT NOT NULL DEFAULT 'queued',
              created DOUBLE PRECISION NOT NULL, updated DOUBLE PRECISION NOT NULL, available DOUBLE PRECISION NOT NULL,
              lease DOUBLE PRECISION NOT NULL DEFAULT 0, attempts BIGINT NOT NULL DEFAULT 0,
              deliveries BIGINT NOT NULL DEFAULT 1, result TEXT NOT NULL DEFAULT '{}',
              issue BIGINT NOT NULL DEFAULT 0, intent TEXT, error TEXT);
CREATE INDEX runnable ON jobs(state,available,lease);
CREATE INDEX episode ON jobs(episode);
CREATE TABLE dispatch (singleton BIGINT PRIMARY KEY CHECK(singleton=1), token TEXT NOT NULL, deadline DOUBLE PRECISION NOT NULL, attempts BIGINT NOT NULL);
CREATE TABLE spi_card_receipts (
              episode TEXT PRIMARY KEY, receipt TEXT NOT NULL);
CREATE TABLE spi_links (
              episode TEXT PRIMARY KEY, event_key TEXT NOT NULL, revision BIGINT NOT NULL,
              url TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'pending',
              available DOUBLE PRECISION NOT NULL DEFAULT 0, lease DOUBLE PRECISION NOT NULL DEFAULT 0,
              owner TEXT, attempts BIGINT NOT NULL DEFAULT 0, error TEXT,
              acknowledgement TEXT NOT NULL DEFAULT '{}');
CREATE TABLE spi_card_discovery(episode TEXT PRIMARY KEY,available DOUBLE PRECISION NOT NULL DEFAULT 0,attempts BIGINT NOT NULL DEFAULT 0,error TEXT);
CREATE TABLE spi_primary_backfill(job_id TEXT PRIMARY KEY,available DOUBLE PRECISION NOT NULL DEFAULT 0,attempts BIGINT NOT NULL DEFAULT 0,error TEXT);
CREATE TABLE telegram_receipts (
            event_key TEXT NOT NULL, episode TEXT NOT NULL, card_key TEXT NOT NULL,
            chat_id BIGINT NOT NULL, message_id BIGINT NOT NULL,
            PRIMARY KEY(event_key,card_key,chat_id,message_id));
CREATE TABLE telegram_receipt_events (
            event_key TEXT PRIMARY KEY, episode TEXT NOT NULL, status TEXT NOT NULL,
            observed BIGINT NOT NULL DEFAULT 0, unknown BIGINT NOT NULL DEFAULT 0);
CREATE TABLE job_failure_budget (
              job_id TEXT PRIMARY KEY REFERENCES jobs(id) ON DELETE CASCADE,
              failures BIGINT NOT NULL DEFAULT 0);
CREATE TABLE llm_rate_metadata (job_id TEXT PRIMARY KEY, metadata TEXT NOT NULL);
CREATE TABLE llm_admission (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tokens BIGINT NOT NULL, expires DOUBLE PRECISION NOT NULL, active BIGINT NOT NULL);
CREATE TABLE snapshot_budget (
              job_id TEXT PRIMARY KEY REFERENCES jobs(id), replacements BIGINT NOT NULL, retained TEXT NOT NULL);
CREATE TABLE match_review_v3 (
              job_id TEXT PRIMARY KEY REFERENCES jobs(id) ON DELETE CASCADE,
              progress TEXT NOT NULL);
CREATE TABLE operator_retry_audit (nonce TEXT NOT NULL, job_id TEXT NOT NULL, authorization_hash TEXT NOT NULL, pre_row_hash TEXT NOT NULL, executed_at DOUBLE PRECISION NOT NULL, reason TEXT NOT NULL, explicit_change TEXT NOT NULL, manifest_digest TEXT NOT NULL, post_row_hash TEXT NOT NULL, PRIMARY KEY(nonce,job_id));
CREATE TABLE workflow_wait_owner (
                job_id TEXT PRIMARY KEY REFERENCES jobs(id),
                execution_id TEXT UNIQUE NOT NULL, revision TEXT NOT NULL,
                fence TEXT NOT NULL, stage TEXT NOT NULL,
                phase TEXT NOT NULL, due DOUBLE PRECISION NOT NULL, expires DOUBLE PRECISION NOT NULL,
                deadline DOUBLE PRECISION NOT NULL, request_fence TEXT, response TEXT, request_stage TEXT);
CREATE TABLE workflow_execution_tombstone (execution_id TEXT PRIMARY KEY);
CREATE TABLE workflow_empty_claim (execution_id TEXT PRIMARY KEY,revision TEXT NOT NULL);
CREATE TABLE queue_operator_actions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id TEXT NOT NULL REFERENCES jobs(id),
                action TEXT NOT NULL, at DOUBLE PRECISION NOT NULL,
                previous_state TEXT NOT NULL, previous_error TEXT, previous_updated DOUBLE PRECISION NOT NULL,
                source TEXT NOT NULL CHECK(source='private-sso-queue-ui'));
CREATE TABLE analysis_output_budget (
              job_id TEXT NOT NULL REFERENCES jobs(id), input_digest TEXT NOT NULL,
              failures BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(job_id,input_digest));
